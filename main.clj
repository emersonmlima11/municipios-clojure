;Função que pega todas as populações
(defn populacao-municipios [lista-municipios]
    (map :populacao lista-municipios))

;Função para calcular a população total
(defn calcular-populacao-total [lista-municipios]
    (reduce + (populacao-municipios lista-municipios))
    )

;Função que pega todas as areas
(defn areas-municipios [lista-municipios]
    (map :area lista-municipios))

;Função para calcular a população total
(defn calcular-area-total [lista-municipios]
    (reduce + (areas-municipios lista-municipios))
    )

;Função para calcular a população total de uma região
(defn calcular-populacao-total-por-regiao [regiao lista-municipios]
    (comp calcular-populacao-total (partial municipios-por-regiao regiao) lista-municipios)
    )

;Função de ordem superior que criar uma função que filtra se o territorio é de certo tamanho
(defn filtro-populacao-minima [populacao-minima]
    (fn [m] (>= (:populacao m) populacao-minima)))

;Função para dizer se uma cidade é de grande porte
(def municipio-grande-porte? (filtro-populacao-minima 100000))

;Função que filtra todos os municipios de grande porte
(defn buscar-cidades-grandes [lista-municipios]
    (filter municipio-grande-porte? lista-municipios))

;Função que filtra todos os municipios acima de um valor
(defn buscar-cidades-acima-de
  [limite lista-municipios]
  (filter (filtro-populacao-minima limite) lista-municipios))

;Função recursiva para contar e classificar os municípios (pequenos, medias e grandes) por população

(defn agrupar-por-faixa-populacional [lista-municipios]
    ;;Adicionar comentario de o por que usar recursão
    (loop [lista lista-municipios
           pequenos 0
           medios 0
           grandes 0]
        (if (empty? lista)
            {:municipios-pequenos pequenos
             :municipios-medios medios
             :municipios-grandes grandes}

            (let [municipio-atual (first lista) populacao (:populacao municipio-atual)
                  resto-da-lista (rest lista)]

                (cond
                    (< populacao 20000)
                    (recur resto-da-lista (inc pequenos) medios grandes)
                    
                    (<= populacao 100000)
                    (recur resto-da-lista pequenos (inc medios) grandes)

                    :else (recur resto-da-lista pequenos medios (inc grandes))
                    )
                )
            )
        )
    )



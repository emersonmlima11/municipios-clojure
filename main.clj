;Função para Calcular Densidade Demográfica de Um Município Passando Um Mapa
(defn densidade-municipio [municipio] 
    (/ (:populacao municipio) (:area municipio)))

;Função para Calcular Densidade Demográfica de Um Município Passando Seu Nome
(defn densidade-por-nome [nome lista-municipios] 
  (let [municipio-encontrado (first (filter (fn [m] (= (:municipio m) nome)) lista-municipios))]
    (if municipio-encontrado
      (densidade-municipio municipio-encontrado)
      "Municipio não encontrado")))

;Função para extrair o nome de um município específico
(defn nomes-municipios [lista-municipios]
    (map :municipio lista-municipios))

;Função que busca nome de municipios por região
(defn nomes-municipios-por-regiao [regiao lista-municipios]
    (let [cidades-filtradas (filter(fn [m] (= (:mesorregiao m) regiao)) lista-municipios)]
        (nomes-municipios cidades-filtradas)))

;Função que extrai os municipios por regiao
(defn municipios-por-regiao [regiao lista-municipios]
    (filter (fn [m] (= (:mesorregiao m) regiao)) lista-municipios)
    )

